import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { createPreparationGate, createSyntheticPreparationVerifier, createMemorySourceBinding, createApprovedExportBinding,
  createAuditedContextBuilder, createSyntheticAuditSink, createContextHandoff,
  createSyntheticUseAuthorizationProvider } from '@definitely-secure-studio/platform/context-builder';
import { identity, digest } from '../src/context-builder/request.js';
import { MockTextAdapter } from '../src/prompt-sdk/index.js';

// Public synthetic scenario and independently supplied fixture approvals only.
export async function createExample({ structured = false, privateContext = false } = {}) {
  const s = JSON.parse(await readFile(new URL('../tests/fixtures/context-builder-lexical-v1.json', import.meta.url)));
  if (structured) {
    s.prompt.output = { kind: 'json', media_type: 'application/json', description: 'Synthetic JSON facts.' };
    s.prompt.capabilities.required.push('structured-output'); s.request.target.identity = identity(s.prompt);
  }
  if (privateContext) {
    const source = s.request.sources[0]; source.kind = 'approved-private'; source.classification = 'internal';
    source.reference = { kind: 'opaque-artifact', handle: 'urn:uuid:00000000-0000-4000-8000-000000000040' };
    const manifest = s.result.package.manifest;
    manifest.sources[0].kind = 'approved-private'; manifest.sources[0].classification = 'internal'; delete manifest.sources[0].artifact;
    manifest.sections[0].classification = 'internal'; manifest.classification = 'internal';
    s.result.package.manifest_identity = identity(manifest);
  }
  const state = { at: s.request.evaluation_time };
  const owner = 'urn:uuid:00000000-0000-4000-8000-000000000080';
  const synthetic = createSyntheticPreparationVerifier([{ decision_id: owner, decision: 'allow', owner_id: owner,
    preparation_reference: s.request.preparation_reference, request_identity: identity(s.request), caller_id: s.request.caller_id,
    target: s.request.target, purpose: s.request.purpose, max_classification: s.request.max_classification,
    not_before: '2026-09-15T00:00:00Z', review_after: s.request.review_after, expires_at: s.request.expires_at }]);
  const bytes = Buffer.from(s.raw_sources[0].text), source = s.request.sources[0];
  const artifact = { byte_size: bytes.length, sha256: digest(bytes), media_type: source.media_type };
  const binding = privateContext
    ? createApprovedExportBinding({ source, artifact, readExport: async () => (async function* () { yield bytes; })() })
    : createMemorySourceBinding({ source, bytes, artifact });
  const gate = createPreparationGate({ mode: 'synthetic', verifier: synthetic.verifier, decisionOwners: [owner],
    sourceBindings: [binding],
    getTime: () => state.at });
  let counter = 900;
  const sink = createSyntheticAuditSink({ makeReference: () => `urn:uuid:00000000-0000-4000-8000-${String(counter++).padStart(12, '0')}` });
  const builder = createAuditedContextBuilder({ gate, mode: 'synthetic', sink, getTime: () => state.at });
  // This is an explicit synthetic approval of the known golden package, not approval generated by the Builder.
  const approval = { build_id: s.request.build_id, correlation_id: s.request.correlation_id,
    request_identity: identity(s.request), package_identity: s.result.package.manifest_identity, authorization: s.authorization };
  const authorizationProvider = createSyntheticUseAuthorizationProvider({ approvals: [approval] });
  const config = { builder, mode: 'synthetic', authorizationProvider, getTime: () => state.at, executionClock: () => Date.parse(state.at) };
  const handoff = createContextHandoff(config);
  const input = { buildInput: { request: s.request, prompt: s.prompt, callerId: s.request.caller_id },
    inputValues: { item: 'blue cube', attributes: {} }, executionOptions: {
      execution_id: 'exec_builder_example_0001', idempotency_key: 'idem_builder_example_0001',
      target: { adapter_id: 'studio.mock.text', provider_id: 'studio-mock', model_id: 'mock-text-v1' },
      capabilities: { required: structured ? ['text-generation', 'structured-output'] : ['text-generation'], optional: [] },
      expected_output: structured ? { kind: 'json', media_type: 'application/json', validation: 'json-syntax' } : { kind: 'text', media_type: 'text/plain', validation: 'none' },
      delegation: { caller_id: 'builder.example', human_owner: 'andrewperis', purpose: s.request.purpose,
        authority_reference: 'https://github.com/DefinitelySecureStudio/studio/issues/83' },
      observability: { retention: 'metadata-only', capture_prompt: false, capture_output: false }
    } };
  const adapter = new MockTextAdapter({ content: structured ? '{"facts":["synthetic"]}' : 'Synthetic approved response.' });
  const structuredOutput = structured ? { processing_id: 'builder_structured_0001', rawRetention: 'identity-only', providerConstraintMode: 'adapter-emulated' } : undefined;
  return { handoff, input, adapter, structuredOutput, config, approval, state, sink };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const structured of [false, true]) {
    const e = await createExample({ structured });
    const result = await e.handoff.execute(e.input, { adapter: e.adapter, structuredOutput: e.structuredOutput });
    // Status only: protected packages, outputs, rendered prompts and identifiers are not logged.
    console.log(JSON.stringify({ scenario: structured ? 'structured' : 'text', status: result.status }));
    if (result.status !== 'succeeded') process.exitCode = 1;
  }
}
